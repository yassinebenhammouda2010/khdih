const container =
    document.getElementById("adhkar-container");

const categoryButtons =
    document.querySelectorAll(".category-button");


// ========================================
// عرض الأذكار
// ========================================

function displayAdhkar(category) {

    container.innerHTML = "";

    const list = adhkar[category];

    if (!list) {
        container.innerHTML =
            "<p>لا توجد أذكار في هذا القسم.</p>";
        return;
    }

    list.forEach((dhikr) => {

        let currentCount = 0;

        const card =
            document.createElement("div");

        card.className = "dhikr-card";

        const text =
            dhikr.text.replace(/\n/g, "<br>");

        // الأذكار التي ليس لها عدد محدد
        if (dhikr.count === null) {

            card.innerHTML = `
                <h3 class="dhikr-title">
                    ${dhikr.title}
                </h3>

                <p class="dhikr-text">
                    ${text}
                </p>

                <div class="dhikr-footer">
                    <span class="dhikr-source">
                        ${dhikr.source}
                    </span>

                    <span class="dhikr-grade">
                        ${dhikr.grade}
                    </span>
                </div>
            `;

            container.appendChild(card);
            return;
        }


        // الأذكار ذات العدد المحدد
        card.innerHTML = `
            <h3 class="dhikr-title">
                ${dhikr.title}
            </h3>

            <p class="dhikr-text">
                ${text}
            </p>

            <div class="dhikr-info">
                <span class="dhikr-source">
                    ${dhikr.source}
                </span>

                <span class="dhikr-grade">
                    ${dhikr.grade}
                </span>
            </div>

            <div class="dhikr-footer">

                <span class="dhikr-count">
                    0 / ${dhikr.count}
                </span>

                <button class="dhikr-button">
                    📿 تكرار
                </button>

            </div>
        `;


        const button =
            card.querySelector(".dhikr-button");

        const countElement =
            card.querySelector(".dhikr-count");


        button.addEventListener(
            "click",
            () => {

                currentCount++;

                countElement.textContent =
                    `${currentCount} / ${dhikr.count}`;


                if (
                    currentCount >= dhikr.count
                ) {

                    button.disabled = true;

                    button.textContent =
                        "✓ اكتمل";

                    card.classList.add(
                        "completed"
                    );
                }
            }
        );


        container.appendChild(card);
    });
}


